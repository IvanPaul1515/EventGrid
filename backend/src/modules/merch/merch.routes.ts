import {Router} from 'express';
import {z} from 'zod';
import {authenticateToken} from '../../middleware/auth.js';
import {editionContext} from '../../middleware/editionContext.js';
import {requireAdmin,requireAnyRole,requireOperatorOrAdmin} from '../../middleware/rbac.js';
import {MerchService as M} from './merch.service.js';
import {ItemSchema,AssignSchema,MovementSchema} from './merch.dto.js';
const router=Router({mergeParams:true}),id=z.string().uuid(),reason=z.string().trim().min(5).max(500);
router.use(authenticateToken,editionContext);
const route=(method:'get'|'post'|'put',path:string,guard:any,fn:(r:any)=>Promise<any>)=>router[method](path,guard,async(r,s,n)=>{try{const data=await fn(r);if(method!=='get')M.changed(r.eventId!);s.json({data});}catch(e){n(e);}});
route('get','/',requireAnyRole,r=>M.list(r.eventId));
route('get','/shirt-report',requireAnyRole,r=>M.shirtReport(r.eventId));
route('get','/registration/:id',requireAnyRole,r=>M.forRegistration(r.eventId,id.parse(r.params.id)));
route('post','/',requireAdmin,r=>M.create(r.eventId,r.user.id,ItemSchema.parse(r.body)));
route('put','/:id',requireAdmin,r=>M.configure(r.eventId,r.user.id,id.parse(r.params.id),ItemSchema.parse(r.body)));
route('post','/:id/receive',requireAdmin,r=>M.receive(r.eventId,r.user.id,id.parse(r.params.id),MovementSchema.parse(r.body)));
route('post','/:id/assign',requireAdmin,r=>M.assign(r.eventId,r.user.id,id.parse(r.params.id),AssignSchema.parse(r.body)));
route('post','/:id/freeze',requireAdmin,r=>M.freeze(r.eventId,r.user.id,id.parse(r.params.id),reason.parse(r.body.reason)));
route('post','/:id/release',requireAdmin,r=>M.release(r.eventId,r.user.id,id.parse(r.params.id),id.parse(r.body.allocationId),reason.parse(r.body.reason)));
route('post','/deliver/:id',requireOperatorOrAdmin,r=>M.deliver(r.eventId,r.user.id,id.parse(r.params.id)));
export default router;
